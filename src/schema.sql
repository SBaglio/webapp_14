CREATE TABLE IF NOT EXISTS USERDATA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(64) NOT NULL,
    firstName varchar(64 ) NOT NULL,
    lastName varchar(64) NOT NULL,
    birthDate Date NOT NULL,
    email varchar(256) NOT NULL,
    numAllenamenti int NOT NULL,
    signupDate Date NOT NULL

    FOREIGN KEY (username) REFERENCES USERS(username) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS USER_PRO_PROGRAMMI (
    username varchar(64) NOT NULL,
    idProg BIGINT NOT NULL,
    FOREIGN KEY(username) REFERENCES userdata(username) ON DELETE CASCADE
    FOREIGN KEY(idProg)  REFERENCES programmi_personalizzati(id)
);

CREATE TABLE IF NOT EXISTS PROGRAMMI_PERSONALIZZATI (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nomeEs varchar(64) NOT NULL,
    numSerie int NOT NULL,
    numRep int NOT NULL,
    kcal float NOT NULL
    numAllenamenti int NOT NULL
);

CREATE TABLE IF NOT EXISTS RECENSIONI (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(64) NOT NULL,
    recensione varchar(1500),
    FOREIGN KEY(username) REFERENCES userdata(username)
);


CREATE TABLE IF NOT EXISTS USERS (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(64) NOT NULL UNIQUE,
    password varchar(256) NOT NULL,
    enabled INT NOT NULL
);

CREATE TABLE IF NOT EXISTS AUTHORITIES (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(64) NOT NULL,
    authority varchar(64) NOT NULL

    FOREIGN KEY (username) REFERENCES USERS(username) ON DELETE CASCADE
);
